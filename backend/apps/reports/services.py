def _timeline_detail(e: dict) -> str:
    p, t = e["payload"], e["event_type"]
    if t == "challenge.result":
        return f"{p.get('type', '')}: {p.get('result', '')}. {p.get('reason', '')}".strip()
    if t in ("challenge.issued", "challenge.generated", "challenge.approved", "challenge.regenerated", "challenge.officer_issued"):
        return p.get("type", "")
    if t == "challenge.type_changed":
        return f"{p.get('from', '')} -> {p.get('to', '')}"
    if t == "session.terminated":
        return p.get("reason", "")
    if t == "document.uploaded":
        return p.get("doc_type", "")
    if t == "documents.checked":
        return p.get("status", "")
    return ""


def canonical(report: dict) -> dict:
    """JSON round-trip so the stored and the hashed forms are identical."""
    return json.loads(json.dumps(report, default=str))


def digest(report: dict) -> str:
    return hashlib.sha256(json.dumps(canonical(report), sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def build_report(s: VerificationSession, decision: dict | None = None) -> dict:
    from apps.documents.services import document_summary  # lazy: documents depends on the evidence layer
    d = decision or current_decision(s)
    rt = get_runtime()
    events = list_events(s.id)
    chain = verify_chain(str(s.id), events)
    summary = {x["detector_name"]: x for x in d["signal_summary"]}
    detectors = []
    for name in dict.fromkeys([*rt.registry.enabled_names(), *summary]):
        x = summary.get(name)
        detectors.append({"detector": name, "label": DETECTOR_LABEL.get(name, name), "status": x["status"] if x else "no_samples", "samples": x["n_samples"] if x else 0,
                          "usable_samples": x["n_usable"] if x else 0, "median_score": x["score"] if x else None, "highest_score": x["max_score"] if x else None,
                          "threshold": x["threshold"] if x else None, "flagged": bool(x and x["flagged"]), "error_code": x["error_code"] if x else None})
    challenges = [{"number": i, "type": c.challenge_type, "text": c.challenge_text, "result": c.result or ("expired" if c.status == "expired" else "not answered"),
                   "reason": c.reason, "measured": c.measured, "issued_at": iso(c.issued_at)}
                  for i, c in enumerate(Challenge.objects.filter(session=s).order_by("issued_at"), 1)]
    timeline = [{"time": e["timestamp"], "event": TIMELINE_EVENTS[e["event_type"]], "detail": _timeline_detail(e)}
                for e in events if e["event_type"] in TIMELINE_EVENTS]
    secs = int((s.completed_at - s.started_at).total_seconds()) if s.started_at and s.completed_at else None
    plain = plain_language(d)
    return canonical({
        "report_version": "2", "generated_at": iso(timezone.now()),
        "session": {"id": str(s.id), "customer": s.owner.username if s.owner_id else None, "status": s.status, "created_at": iso(s.created_at),
                    "started_at": iso(s.started_at) if s.started_at else None, "completed_at": iso(s.completed_at) if s.completed_at else None,
                    "duration_seconds": secs, "consent_given": s.consent_given, "consent_timestamp": iso(s.consent_timestamp) if s.consent_timestamp else None,
                    "policy_version": s.policy_version, "approval_status": s.approval_status,
                    "approved_by": s.approved_by.username if s.approved_by_id else None, "approved_at": iso(s.approved_at) if s.approved_at else None},
        "outcome": {"risk_level": d["risk_level"], "headline": d["headline"], "summary": d["summary"], "rule": d["rule"], "rule_text": d["rule_text"],
                    "indicators": d["indicators"], "evidence_completeness": d["evidence_completeness"], "human_review_required": True},
        "reasons": d["reason_details"], "next_steps": d["next_steps"], "documents": document_summary(s),
        "families": [{k: f.get(k) for k in ("id", "label", "status", "score", "threshold", "samples", "usable", "quality", "flagged", "positive", "explain")} for f in d.get("families", [])],
        "session_analysis": session_analysis(s, d), "identity": identity_section(s), "network": network_section(s),
        "challenges": challenges, "challenge_summary": d["challenge_summary"], "detectors": detectors, "timeline": timeline,
        "evidence_integrity": {"events_checked": chain["checked"], "chain_valid": chain["valid"], "note": chain["note"]},
        "limitations": LIMITATIONS, "plain_language": plain,
    })


COLOUR_LEGEND = [
    {"colour": "GREEN", "meaning": "Everything we could check looked normal, enough different checks were done, and nothing looked wrong. A good sign, not a guarantee."},
    {"colour": "AMBER", "meaning": "At least one thing looked unusual or could not be confirmed. An officer should look at the marked items before deciding."},
    {"colour": "RED", "meaning": "Several checks looked wrong, or one very serious check failed (face, voice, camera). Treat as high risk and verify the person another way."},
    {"colour": "GREY", "meaning": "Not enough good information to say anything. Neither a pass nor a warning. Repeat the check after fixing the gaps."},
]


def plain_language(d: dict) -> dict:
    """The 'in plain words' section at the end of the report: what the colour means, and what each check found, for a reader with no technical background."""
    lvl = d["risk_level"]
    fams = d.get("families") or []
    return {"overall": d.get("overall_explain") or d["summary"], "colour_legend": COLOUR_LEGEND, "result_colour": lvl,
            "by_check": [{"check": f["label"], "colour": {"green": "GREEN", "amber": "AMBER", "red": "RED", "grey": "GREY"}[f["status"]], "in_plain_words": f.get("explain", "")} for f in fams],
            "what_to_do": d["next_steps"],
            "how_decided": "Every check is judged on all of its samples over the whole session, not on one moment. A serious failure in an identity, voice or camera check "
                           "makes the result RED on its own. Otherwise points are added up for the checks that raised a concern. The result can only be GREEN when enough "
                           "independent checks positively confirm the person, the session lasted long enough, requested actions were confirmed by our own video analysis, and video kept arriving."}


def session_analysis(s, d: dict) -> dict:
    """Patterns over the length of the session: how long it ran, challenges over time, response speed, identity similarity over time."""
    t0 = s.started_at or s.created_at
    rows = []
    for c in Challenge.objects.filter(session=s).order_by("created_at", "sequence"):
        lat = int((c.answered_at - c.issued_at).total_seconds() * 1000) if c.answered_at else None
        rows.append({"seq": c.sequence, "type": c.challenge_type, "at_s": int((c.created_at - t0).total_seconds()), "status": c.status, "result": c.result,
                     "verification": c.verification, "response_ms": lat})
    lat = [r["response_ms"] for r in rows if r["response_ms"] is not None]
    from apps.biometrics.summary import face_match_series
    return {"duration_seconds": int((s.completed_at or timezone.now()).timestamp() - t0.timestamp()) if s.started_at else None, "challenges_over_time": rows,
            "median_response_ms": int(sorted(lat)[len(lat) // 2]) if lat else None, "coverage": d.get("coverage"), "challenge_stats": d.get("challenge_summary"),
            "face_similarity_over_time": [{"t": x["t"], "similarity": x["similarity"]} for x in face_match_series(s) if x["similarity"] is not None][-60:]}


def identity_section(s) -> dict:
    from apps.biometrics.summary import summarise
    out = summarise(s)
    out["face_match"].pop("series", None)
    return out


def network_section(s) -> dict:
    from apps.biometrics.models import Observation
    from apps.signals.models import DetectorSignal
    last = DetectorSignal.objects.filter(session=s, detector_name="integrity").order_by("-created_at").first()
    ips = [o.data.get("ip") for o in Observation.objects.filter(session=s, kind="net").order_by("created_at")]
    chk = ((last.details or {}).get("checks") if last else None) or {}
    return {"ips_seen": list(dict.fromkeys(ips)), "ip_check": chk.get("ip"), "camera_check": chk.get("camera"), "notes": ((last.details or {}).get("notes") if last else []) or []}


def report_for(s) -> dict:
    """The report an officer sees or downloads: the frozen one for a finished session, else a live snapshot. Includes the hash check."""
    from apps.evidence.models import EvidenceEvent
    if s.report:
        recorded = EvidenceEvent.objects.filter(session=s, event_type="report.generated").order_by("-seq").first()
        sha = digest(s.report)
        return {**s.report, "snapshot": "stored_at_completion",
                "integrity": {"report_sha256": sha, "matches_evidence_chain": bool(recorded and recorded.payload.get("report_sha256") == sha)}}
    live = build_report(s)
    return {**live, "snapshot": "generated_now", "integrity": {"report_sha256": digest(live), "matches_evidence_chain": None}}
