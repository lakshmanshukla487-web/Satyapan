"""Officer summary report: one self-contained document explaining the risk level and the evidence behind it.

Built when a session completes and frozen on the session (`VerificationSession.report`). Its SHA-256 is recorded in
the hash-chained evidence log (`report.generated`), so an officer can see whether the stored report was changed later.
Never contains raw media, tokens or the customer's password; the customer never receives it."""
